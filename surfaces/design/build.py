"""The design-token generator (ADR 0023, issue #172 / #27):

    python -m surfaces.design.build [--instance NAME] [--out-dir DIR] [--repo-root DIR]

Reads `surfaces/design/tokens.yaml`, optionally merges an instance's own
`instances/<name>/look/tokens.yaml` over it (the override always wins,
tokens it does not mention keep the default value), and writes the result
as `tokens.css` (CSS custom properties, prefix `--ct-`) and `tokens.json`
(the same values as data) into `--out-dir` (default: next to
`tokens.yaml`, so plain `python -m surfaces.design.build` reproduces the
two files the issue names).
"""
from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
DEFAULT_TOKENS_PATH = HERE / "tokens.yaml"

# Every generated tokens.css (the canonical copy and every per-surface copy
# `--out-dir` writes) carries this line -- it is what exempts a file from
# the no-hardcoded-colour scan (surfaces/design/tests/test_no_hardcoded_colors.py).
GENERATED_MARKER = "Generated by `python -m surfaces.design.build` -- do not edit by hand."


def load_tokens(path: Path) -> dict:
    """Parse one `tokens.yaml`-shaped file. Raises if it does not exist --
    a missing override is a configuration error, never a silent no-op."""
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"no tokens file: {path}")
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def deep_merge(base: dict, override: dict) -> dict:
    """`override` wins key by key; a key `override` does not mention keeps
    `base`'s value. Neither input is mutated."""
    result = copy.deepcopy(base)

    def _merge(dst: dict, src: dict) -> None:
        for key, value in src.items():
            if isinstance(value, dict) and isinstance(dst.get(key), dict):
                _merge(dst[key], value)
            else:
                dst[key] = copy.deepcopy(value)

    _merge(result, override)
    return result


def resolve_tokens(repo_root: Path, instance: str | None) -> dict:
    """The default tokens, merged with `instances/<instance>/look/tokens.yaml`
    when `instance` is given. `instance=None` returns the default,
    unmodified, regardless of `repo_root`."""
    default = load_tokens(DEFAULT_TOKENS_PATH)
    if instance is None:
        return default
    override_path = Path(repo_root) / "instances" / instance / "look" / "tokens.yaml"
    override = load_tokens(override_path)
    return deep_merge(default, override)


def _font_face(family: str, rel_path: str) -> str:
    return (
        f'@font-face {{\n'
        f'  font-family: "{family}";\n'
        f'  font-style: normal;\n'
        f'  font-weight: 400;\n'
        f'  font-display: swap;\n'
        f'  src: url("{rel_path}") format("woff2");\n'
        f'}}'
    )


def _color_declarations(color: dict) -> list[str]:
    return [f"  --ct-{name}: {value};" for name, value in color.items()]


def _type_declarations(type_tokens: dict) -> list[str]:
    decls = [
        f'  --ct-font-sans: "{type_tokens["font-sans"]}", system-ui, sans-serif;',
        f'  --ct-font-mono: "{type_tokens["font-mono"]}", ui-monospace, monospace;',
    ]
    decls += [f"  --ct-size-{name}: {px}px;" for name, px in type_tokens["size"].items()]
    decls += [f"  --ct-display-{name}: {px}px;" for name, px in type_tokens["display-size"].items()]
    return decls


def _space_declarations(space: list[int]) -> list[str]:
    return [f"  --ct-space-{value}: {value}px;" for value in space]


def _radius_declarations(radius: list[int]) -> list[str]:
    return [f"  --ct-radius-{value}: {value}px;" for value in radius]


def _motion_declarations(motion: list[int]) -> list[str]:
    return [f"  --ct-motion-{value}: {value}ms;" for value in motion]


def render_css(tokens: dict) -> str:
    """The generated `tokens.css`: one `@font-face` pair, one declaration
    block per theme. Only the default theme carries type/space/radius/
    motion -- the other themes override colour only."""
    themes = tokens["themes"]
    default_theme = themes["default"]
    font_path = tokens["type"]["font-path"]

    lines = [
        "/*",
        " * CoThinker design tokens (ADR 0023, issue #172 / #27).",
        f" * {GENERATED_MARKER}",
        " * Fira Sans / Fira Mono (SIL OFL) font files are not shipped in this public",
        " * repo; the @font-face rules below point at a path the deployment supplies.",
        " */",
        "",
        _font_face(tokens["type"]["font-sans"], f"{font_path}fira-sans-400.woff2"),
        "",
        _font_face(tokens["type"]["font-mono"], f"{font_path}fira-mono-400.woff2"),
        "",
        f'{default_theme["selector"]} {{',
    ]
    lines += _color_declarations(default_theme["color"])
    lines += _type_declarations(tokens["type"])
    lines += _space_declarations(tokens["space"])
    lines += _radius_declarations(tokens["radius"])
    lines += _motion_declarations(tokens["motion"])
    lines.append("}")

    for name, theme in themes.items():
        if name == "default":
            continue
        lines.append("")
        lines.append(f'{theme["selector"]} {{')
        lines += _color_declarations(theme["color"])
        lines.append("}")

    return "\n".join(lines) + "\n"


def render_json(tokens: dict) -> str:
    return json.dumps(tokens, indent=2, sort_keys=True) + "\n"


def build(out_dir: Path, instance: str | None = None, repo_root: Path | None = None) -> tuple[Path, Path]:
    """Write `tokens.css` and `tokens.json` into `out_dir`. Returns their paths."""
    tokens = resolve_tokens(repo_root=repo_root or REPO_ROOT, instance=instance)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    css_path = out_dir / "tokens.css"
    json_path = out_dir / "tokens.json"
    css_path.write_text(render_css(tokens), encoding="utf-8")
    json_path.write_text(render_json(tokens), encoding="utf-8")
    return css_path, json_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m surfaces.design.build")
    parser.add_argument("--instance", default=None, metavar="NAME",
                         help="merge instances/<name>/look/tokens.yaml over the default")
    parser.add_argument("--out-dir", default=str(HERE), metavar="DIR",
                         help="directory to write tokens.css/tokens.json into (default: next to tokens.yaml)")
    parser.add_argument("--repo-root", default=str(REPO_ROOT), metavar="DIR",
                         help="repository root, to resolve instances/<name>/look/ (default: this repo)")
    args = parser.parse_args(argv)

    try:
        css_path, json_path = build(out_dir=args.out_dir, instance=args.instance, repo_root=Path(args.repo_root))
    except FileNotFoundError as exc:
        print(f"surfaces.design.build: {exc}", file=sys.stderr)
        return 1

    print(f"wrote {css_path}")
    print(f"wrote {json_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
